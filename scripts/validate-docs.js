#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const errors = [];
function exists(rel) { return fs.existsSync(path.join(root, rel)); }
function checkReference(rel, source) {
  const clean = rel.split('#')[0].split('?')[0];
  if (!clean || /^(https?:|mailto:|tel:|#)/i.test(clean)) return;
  const resolved = path.resolve(root, path.dirname(source), clean);
  if (!fs.existsSync(resolved)) errors.push(source + ' -> missing local reference: ' + rel);
}
const manifestPath = path.join(root, 'SKILL_MANIFEST.json');
let manifest;
try { manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8')); }
catch (error) { errors.push('SKILL_MANIFEST.json is invalid JSON: ' + error.message); }
if (manifest) {
  const refs = new Set();
  const pathLike = /^(?!node\s)(?!npm\s)(?!pnpm\s)(?!yarn\s)(?!bun\s)[A-Za-z0-9_./-]+\.(md|js|json|ya?ml)$/;
  function collect(value) {
    if (typeof value === 'string' && pathLike.test(value)) refs.add(value);
    else if (Array.isArray(value)) value.forEach(collect);
    else if (value && typeof value === 'object') Object.values(value).forEach(collect);
  }
  collect(manifest);
  for (const ref of refs) if (!exists(ref)) errors.push('Manifest reference missing: ' + ref);
  console.log('Manifest file references checked: ' + refs.size);
}
const markdownFiles = [];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['.git', 'node_modules'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.isFile() && entry.name.endsWith('.md')) markdownFiles.push(full);
  }
}
walk(root);
for (const full of markdownFiles) {
  // BRAIN.md is generated by concatenating source documents; its relative links
  // intentionally point to original module paths and are not relative to BRAIN.md.
  if (path.basename(full) === 'BRAIN.md') continue;
  const rel = path.relative(root, full).replace(/\\/g, '/');
  const fence = String.fromCharCode(96).repeat(3);
  const content = fs.readFileSync(full, 'utf8').replace(new RegExp(fence + '[\\s\\S]*?' + fence, 'g'), '');
  const linkPattern = /!?\[[^\]]*\]\(([^)]+)\)/g;
  let match;
  while ((match = linkPattern.exec(content))) {
    const destination = match[1].trim().replace(/^<|>$/g, '').split(/\s+/)[0];
    checkReference(destination, rel);
  }
}
for (const required of ['scripts/resolve-paths.js', 'scripts/website-builder.js', 'scripts/audit-engine.js']) {
  if (!exists(required)) errors.push('Required runtime file missing: ' + required);
}
if (errors.length) {
  console.error('\nDocumentation validation failed (' + errors.length + '):');
  errors.forEach((error) => console.error(' - ' + error));
} else {
  console.log('Markdown local links and manifest paths: PASS (' + markdownFiles.length + ' Markdown files scanned; BRAIN.md compiled-link exception documented).');
}
process.exitCode = errors.length ? 1 : 0;
